-- Retour dev senior (Bug 36b) : on n'autorise plus le « max possible »
-- (text illimité). Les ENTITÉS deviennent la source de vérité du schéma
-- (DDL pur via @Column(length=N)) et Postgres s'aligne via cette migration.
--
-- Paliers resserrés (validés) : 64 / 128 / 256 / 512 / 1024 / 4096.
--   64   : code, statut, type, slug, rôle, téléphone, couleur, heure, emoji
--   128  : name, title, label, ville, tier, hash (SHA/bcrypt)
--   256  : address, email, ip_address
--   512  : url, token, path, image, user_agent, device
--   1024 : description, message, notes, reason, comment, summary, details
--   4096 : content, preamble (texte long)
--
-- NON DESTRUCTIVE par construction : chaque palier N a été vérifié >= au
-- max(length()) réel observé en base (oneclick_enterprise, schéma canonique).
-- Les longueurs ici == @Column(length=N) côté entités (ddl-auto=validate).
-- Tables framework (event_publication / flyway_schema_history) exclues.
